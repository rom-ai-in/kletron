/**
 * Build a LiteLLM proxy config from environment variables.
 * No secrets are hardcoded — callers pass env explicitly.
 */
export interface LiteLLMEnv {
  LITELLM_MASTER_KEY?: string;
  LITELLM_PORT?: string;
  EVERYWARE_API_BASE?: string;
  EVERYWARE_API_KEY?: string;
  EVERYWARE_MODEL?: string;
  KLETRON_CLIENT_ID?: string;
}

export interface LiteLLMConfigDoc {
  model_list: Array<{
    model_name: string;
    litellm_params: {
      model: string;
      api_base: string;
      api_key: string;
      custom_llm_provider: string;
    };
  }>;
  general_settings: {
    master_key: string;
    alerting: string[];
  };
  litellm_settings: {
    drop_params: boolean;
    set_verbose: boolean;
  };
  kletron: {
    clientId: string;
    note: string;
  };
}

export function generateLiteLLMConfig(env: LiteLLMEnv): LiteLLMConfigDoc {
  const apiBase = env.EVERYWARE_API_BASE ?? "https://everyware.example.invalid/v1";
  const apiKey = env.EVERYWARE_API_KEY ?? "sk-everyware-demo-not-real";
  const model = env.EVERYWARE_MODEL ?? "everyware-demo-small";
  const masterKey = env.LITELLM_MASTER_KEY ?? "sk-demo-master-not-real";

  return {
    model_list: [
      {
        model_name: "kletron-default",
        litellm_params: {
          model: `openai/${model}`,
          api_base: apiBase,
          api_key: apiKey,
          custom_llm_provider: "openai",
        },
      },
    ],
    general_settings: {
      master_key: masterKey,
      alerting: [],
    },
    litellm_settings: {
      drop_params: true,
      set_verbose: false,
    },
    kletron: {
      clientId: env.KLETRON_CLIENT_ID ?? "demo-client",
      note: "Demo config only. Point EVERYWARE_* at the real ELCA endpoint per client pile. Never commit real keys.",
    },
  };
}

export function renderLiteLLMYaml(doc: LiteLLMConfigDoc): string {
  // Minimal YAML without adding a dependency
  const m = doc.model_list[0];
  return `# Generated by kletron-platform — do not commit real secrets
model_list:
  - model_name: ${m.model_name}
    litellm_params:
      model: ${m.litellm_params.model}
      api_base: ${m.litellm_params.api_base}
      api_key: \${EVERYWARE_API_KEY}
      custom_llm_provider: ${m.litellm_params.custom_llm_provider}
general_settings:
  master_key: \${LITELLM_MASTER_KEY}
  alerting: []
litellm_settings:
  drop_params: true
  set_verbose: false
# kletron.clientId: ${doc.kletron.clientId}
# ${doc.kletron.note}
`;
}

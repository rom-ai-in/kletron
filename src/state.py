from typing import TypedDict, List, Dict, Optional, Any, Annotated
from langgraph.graph.message import add_messages
from langchain_core.messages import BaseMessage

class AgentState(TypedDict):
    """
    State schema for the Multi-Agent Coding System.
    """
    messages: Annotated[List[BaseMessage], add_messages]  # Chat history
    
    # Context
    user_request: str
    current_plan: Optional[str]  # The plan generated by the Planner
    current_task: Optional[str]  # The specific subtask currently being executed
    
    # Working Memory
    files_content: Dict[str, str]  # Cache of read files {path: content}
    terminal_output: Optional[str] # Last command output
    review_feedback: Optional[str] # Feedback from Reviewer
    
    # Routing
    next_agent: Optional[str] # Decision by Supervisor
    
    # Status
    is_complete: bool
